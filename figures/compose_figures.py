def ink_box(png):
    """(x0, y0, x1, y1, W, H) of the drawn part of an image, in its own pixels."""
    with Image.open(png) as im:
        if im.mode in ('RGBA', 'LA', 'P'):
            im = im.convert('RGBA')
            flat = Image.new('RGB', im.size, 'white')
            flat.paste(im, mask=im.getchannel('A'))
        else:
            flat = im.convert('RGB')
        a = np.asarray(flat).astype(int)
    m = crop_structures.ink(a)
    r = np.where(m.any(1))[0]
    c = np.where(m.any(0))[0]
    return c[0], r[0], c[-1] + 1, r[-1] + 1, a.shape[1], a.shape[0]


def place_ink(page, png, ink_rect):
    """Place `png` so its drawn part lands centred on `ink_rect`, as large as it fits.

    The published structure images carry a margin of their own, and a fresh crop carries a
    different one, so lining the FILES up would put the two structures at different sizes.
    Lining up what is drawn inside them does not: the target rectangles are the ink boxes
    measured off the published pages, and whatever margin the replacement file has simply
    hangs outside them, empty.
    """
    x0, y0, x1, y1 = ink_box(png)[:4]
    W, H = ink_box(png)[4:]
    tx0, ty0, tx1, ty1 = ink_rect
    s = min((tx1 - tx0) / (x1 - x0), (ty1 - ty0) / (y1 - y0))
    cx, cy = (tx0 + tx1) / 2, (ty0 + ty1) / 2
    ox, oy = cx - (x0 + x1) / 2 * s, cy - (y0 + y1) / 2 * s
    page.insert_image(pymupdf.Rect(ox, oy, ox + W * s, oy + H * s),
                      filename=png, keep_proportion=True)


def pair_figure(doc, key):
    spec = PAIRS[key]
    page = doc.new_page(width=spec['page'][0], height=spec['page'][1])

    # --- the two-panel fatband across the bottom, at the published rectangle -----
    # The published rectangle fixes where the band sits and how wide it is; its height
    # follows the panel's own aspect, so a regenerated panel that crops a little
    # differently still fills the width and keeps its proportions rather than being
    # squashed into last time's rectangle.
    band, band_rect = spec['band']
    x0, _, x1, y1 = band_rect
    place_image(page, f'{PANELS}/{band}',
                (x0, y1 - (x1 - x0) / image_aspect(f'{PANELS}/{band}'), x1, y1))
    h_sigma(page, *PAIR_HSIG)

    for col, cx, (lx, ly), tag in zip(spec['cols'], PAIR_CX, PAIR_LETTERS, '(a) (b)'.split()):
        # The structure keeps its own aspect and is centred in the published rectangle,
        # so a re-crop that is a few per cent taller or wider than the published image
        # stays inside the space the layout gives it.
        png = os.path.join(HERE, 'structures', f"{col['name']}.png")
        print(f"  using figures/structures/{col['name']}.png")
        place_ink(page, png, col['ink'])

        for line, base in zip(col['values'], PAIR_BASELINES):
            text_centre(page, line, cx, base, PAIR_TEXT_PT)
        # only `p/d` is italic on the last line, as published
        text_centre_runs(page, (('p/d', True), (f" electron ratio: {col['ratio']}", False)),
                         cx, PAIR_BASELINES[4], PAIR_TEXT_PT)
        letter(page, tag, lx, ly, size=PAIR_LETTER_PT)
    return key


BUILDERS = {'3': figure3, '4': figure4,
            '5': lambda doc: pair_figure(doc, 'Fig5'),
            'S5': lambda doc: pair_figure(doc, 'SI_5'),
            'S6': lambda doc: pair_figure(doc, 'SI_6')}


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--only', nargs='*', metavar='N')
    a = ap.parse_args()
    if TIMES_BD is None:
        print('[note] Times New Roman not found; panel letters fall back to a base font')
    os.makedirs(OUTDIR, exist_ok=True)
    keys = a.only or list(BUILDERS)
    for k in keys:
        if k not in BUILDERS:
            sys.exit(f'unknown figure {k!r}; choose from {sorted(BUILDERS)}')
        doc = pymupdf.open()
        stem = BUILDERS[k](doc)
        p = os.path.join(OUTDIR, f'{stem}.pdf')
        doc.save(p, garbage=4, deflate=True)
        doc.close()
        print(f'  written: {p}   ({os.path.getsize(p) / 1e6:.2f} MB)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
