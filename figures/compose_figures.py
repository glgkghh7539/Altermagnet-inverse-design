#!/usr/bin/env python3
"""Assemble the published composite figures from the regenerated panels.

Figs. 3, 4, 5 and SI Figs. S5-S6 are composites: plotted panels beside crystal-structure
renderings, arranged in presentation software. This script does that arrangement in code
instead, so the whole figure is reproducible rather than only its plotted halves.

Every plotted panel comes from `Figures_R1/`, placed with `show_pdf_page`, which carries
the source PDF's vector content through unchanged - the text stays text and the lines stay
lines. Nothing is rasterized in the process.

The crystal structures come from one of two places:

  * `../../final_structure/POSCAR_*.png` - the original VESTA renders, 4130 x 1995 px.
    Placed at the sizes used here they exceed 1000 ppi. Available for CoO, CoS, CrS,
    FeAs, FeS and NiS, so Fig. 5 and SI S5-S6 use them.
  * the published PDF itself, for CuO, FeSi, VO and CrSb, which have no `.vesta` file
    and no high-resolution render anywhere in the project. Those are lifted with
    `show_pdf_page` and a clip, which reuses the embedded image object as it is - no
    resampling - but its resolution is what the published figure had: 241 ppi for the
    Fig. 3 pair, 200 ppi for the Fig. 4 pair.

Panel geometry is not guessed. Every target rectangle below was measured off the
published PDF: axes rectangles by finding the black frame in a 200 dpi render, image
rectangles from `page.get_image_info()`. The page size of each composite is the published
page size.

    python figures/compose_figures.py            # all of them -> figures/composed/
    python figures/compose_figures.py --only 3 5
"""
